/**
 * બેઝ URL અને API એન્ડપોઇન્ટ્સ કન્ફિગરેશન
 * -------------------------------------------------------------
 * આ ફાઈલનો ઉપયોગ બધા API એન્ડપોઇન્ટ્સને એક જ જગ્યાએથી મેનેજ કરવા માટે થાય છે.
 * 
 * મુખ્ય ફાયદા:
 * ૧. ભવિષ્યમાં API સર્વરનું ડોમેઈન બદલાય તો ફક્ત અહીં એક જ જગ્યાએ BASE_URL બદલવાનો રહે છે.
 * ૨. આખા પ્રોજેક્ટમાં અલગ-અલગ સ્ક્રીન્સ પર સીધી લિંક્સ લખવી પડતી નથી.
 */

// ૧. મુખ્ય સર્વર બેઝ URL (MAIN SERVER BASE URL)
// લોકલ ટેસ્ટિંગ માટે: 'http://192.168.1.36:8000/api/v1/'
// લાઈવ પ્રોડક્શન સર્વર માટે:
export const BASE_URL = 'https://erp.applified.co.in/demo/public/api/v1/';

// ૨. હેડર કન્ફિગરેશન (HEADER CONFIGURATION)
// API રિક્વેસ્ટમાં JSON ફોર્મેટ સ્વીકારવા માટે:
export const ACCEPT_HEADER = 'application/json';

// -------------------------------------------------------------
// ૩. ઓથેન્ટિકેશન URLS (લૉગિન, રજીસ્ટ્રેશન)
// -------------------------------------------------------------
// લૉગિન API: POST રિક્વેસ્ટમાં ઈમેઈલ અને પાસવર્ડ મોકલવા માટે
export const login_url = BASE_URL + 'login';

// રજીસ્ટ્રેશન API: POST રિક્વેસ્ટમાં નવા યુઝરની વિગતો મોકલવા માટે
export const register_url = BASE_URL + 'register';

// -------------------------------------------------------------
// ૪. ડેશબોર્ડ / હોમ સ્ક્રીન URLS
// -------------------------------------------------------------
// ડેશબોર્ડનું લિસ્ટ મેળવવા માટે:
export const get_dashboard_list_url = BASE_URL + 'get-dashboard-data';

// પ્રોડક્ટ્સ લિસ્ટ API:
export const get_product_url = BASE_URL + 'get-products';

// આઇટમ સિલેક્ટ અથવા ફેવરિટ કરવા માટે:
export const toggle_select_item_url = BASE_URL + 'toggle-select';

// -------------------------------------------------------------
// ૫. પ્રોફાઇલ URLS
// -------------------------------------------------------------
// યુઝર પ્રોફાઇલ ડેટા મેળવવા માટે:
export const get_profile_url = BASE_URL + 'get-profile';

// યુઝર પ્રોફાઇલ અપડેટ કરવા માટે:
export const update_profile_url = BASE_URL + 'update-profile';

// યુઝર એકાઉન્ટ ડિલીટ કરવા માટે:
export const delete_user_url = BASE_URL + 'delete-user';

// -------------------------------------------------------------
// ૬. એપ વર્ઝન URL (નવું અપડેટ ચેક કરવા માટે)
// -------------------------------------------------------------
// પ્લે સ્ટોર કે એપ સ્ટોર પર નવું વર્ઝન છે કે નહીં તે ચેક કરવા માટે:
export const get_version_url = BASE_URL + 'get-version';
